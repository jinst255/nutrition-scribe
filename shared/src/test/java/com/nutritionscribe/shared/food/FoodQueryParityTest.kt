package com.nutritionscribe.shared.food

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Keeps the Kotlin in step with tools/foodsearch.py.
 *
 * The Python reference is what builds the word index and what every benchmark
 * measures, so the two implementations agreeing is load-bearing: if they drift,
 * the numbers in the README describe an app that does not exist, and foods can
 * become unfindable with no error anywhere. That already happened once — the
 * stemmer turned "pancakes" into "pancak" while "pancake" stayed whole.
 *
 * Every expected value below was GENERATED by running the Python. Regenerate
 * rather than hand-edit:
 *
 *     python3 -c "import sys; sys.path.insert(0,'tools'); import foodsearch as F; \
 *                 print(F.preprocess('<the input>'))"
 */
class FoodQueryParityTest {

    @Test
    fun `preprocess matches the python reference`() {
        val cases = listOf(
            "⅓bell peper, carrots, celery" to "0.3333 bell peper, carrots, celery",
            "carrot cake 2 servings" to "2 serving carrot cake",
            "tablespoon and a half of peanut butter" to "1.5 tablespoon of peanut butter",
            "0% Fat Greek yogurt and I had about a cup and 1/4 of it" to
                "0% Fat Greek yogurt and I had about 1.25 cup of it",
            "I just had two hot dogs with some ketchup" to "two hot dogs with some ketchup",
            "1/3 of a pork chop" to "0.3333 of a pork chop",
            "about half a serving of shredded mozzarella cheese" to
                "half serving of shredded mozzarella cheese",
            "milk 2 cups while milk" to "2 cups milk while milk",
            "a couple of eggs" to "couple of eggs",
            "½ cup cottage cheese 4% fat" to "0.5 cup cottage cheese 4% fat",
            "2 and a half cups of rice" to "2.5 cups of rice",
            "this morning I had some protein pancakes" to "some protein pancakes",
            "a few strawberries" to "few strawberries",
            "chicken breast 8oz" to "8 oz chicken breast",
            // Already clean: preprocess must leave these exactly alone.
            "8oz chicken breast" to "8oz chicken breast",
            "2 eggs" to "2 eggs",
            "a banana" to "a banana",
        )
        for ((input, expected) in cases) {
            assertEquals("preprocess($input)", expected, FoodQuery.preprocess(input))
        }
    }

    @Test
    fun `a stated protein figure is not read as a serving weight`() {
        // "20g protein shake" logged twenty grams OF protein powder: the protein
        // was right at 20 g and the calories were 70 instead of 160.
        val cases = listOf(
            Triple("20g protein shake", 20.0, "protein shake"),
            Triple("17g built bar", 17.0, "built bar"),
            Triple("bread which was 6 g of protein", 6.0, "bread which was protein"),
            // "15g butter" really IS fifteen grams of butter — butter is not sold
            // by its protein content, so the number must stay a weight.
            Triple("15g butter", null, "15g butter"),
            Triple("a banana", null, "a banana"),
        )
        for ((input, grams, rest) in cases) {
            val claim = FoodQuery.stripProteinClaim(input)
            assertEquals("grams for $input", grams, claim.grams)
            assertEquals("text for $input", rest, FoodQuery.preprocess(claim.text))
        }
    }

    @Test
    fun `stem folds plurals without eating the word`() {
        // "-es" is only a plural marker after a sibilant or an "o". Stripping it
        // everywhere made "pancakes" into "pancak", so a search for "pancake"
        // could not reach "Pancakes, NFS" and found "Pancake syrup" instead.
        val folds = mapOf(
            "pancakes" to "pancake", "apples" to "apple", "grapes" to "grape",
            "noodles" to "noodle", "juices" to "juice", "waffles" to "waffle",
            "boxes" to "box", "dishes" to "dish", "glasses" to "glass",
            "tomatoes" to "tomato", "potatoes" to "potato", "sandwiches" to "sandwich",
            "berries" to "berry", "eggs" to "egg", "almonds" to "almond",
        )
        for ((plural, singular) in folds) {
            assertEquals(plural, singular, FoodQuery.stem(plural))
            assertEquals("$singular must be its own stem", singular, FoodQuery.stem(singular))
        }
    }

    @Test
    fun `the last word of a query steers the sense`() {
        // English puts the head noun last, USDA puts it first. Without this,
        // "raspberry jam" matched "Raspberries, raw".
        val words = FoodQuery.contentWords("raspberry jam")
        assertTrue(
            "jam should beat the berry",
            FoodQuery.score(words, "Jam") > FoodQuery.score(words, "Raspberries, raw"),
        )
        val pie = FoodQuery.contentWords("apple pie")
        assertTrue(
            "apple pie is a pie",
            FoodQuery.score(pie, "Pie, apple, two crust") > FoodQuery.score(pie, "Apple, raw"),
        )
        // ...but a bare "apple" must still be the fruit.
        val apple = FoodQuery.contentWords("apple")
        assertTrue(
            "a bare apple is the fruit",
            FoodQuery.score(apple, "Apple, raw") > FoodQuery.score(apple, "Pie, apple, two crust"),
        )
    }

    @Test
    fun `a fragment that is not food is not credible`() {
        // Splitting a sentence produces fragments that are not food, and each one
        // still found a nearest row: raw rice for "medium sized", Reese's cups for
        // "1/4 of it". Those calories were added to meals nobody ate.
        assertTrue(!FoodQuery.isCredible("medium sized", "Rice, white, medium-grain, raw, enriched"))
        assertTrue(!FoodQuery.isCredible("of it", "Candies, REESE'S Peanut Butter Cups"))
        assertTrue(FoodQuery.isCredible("cheddar cheese", "Cheese, Cheddar"))
        assertTrue(FoodQuery.isCredible("celery", "Celery, raw"))
    }

    @Test
    fun `splitting on with is offered but not forced`() {
        // "two pancakes with maple syrup" logged the syrup and no pancakes.
        val split = FoodQuery.splitOnWith(listOf("two pancakes with a little maple syrup"))
        assertEquals(listOf("two pancakes", "a little maple syrup"), split)

        // The caller picks whichever reading explains more of the sentence, so
        // tearing "spaghetti with meat sauce" apart has to LOSE on coverage.
        val words = FoodQuery.contentWords("spaghetti with meat sauce")
        val whole = FoodQuery.explained(listOf("Spaghetti with meat sauce"), words)
        val torn = FoodQuery.explained(listOf("Pasta, cooked", "Sauce, NFS"), words)
        assertTrue("the whole dish explains more than its parts", whole > torn)
    }
}
